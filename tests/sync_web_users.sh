#!/usr/bin/env bash
# tests/sync_web_users.sh - rebuild private/web-tokens.yaml (the web app's SIMULATED sign-in list)
# from the users table. Run it after adding, changing or deactivating users; the web API reloads
# by itself when the file changes.
#   token "<email>:demo" -> principal <email>
#   envs:      admins all environments; editors their editable_environments; viewers none
#   flag_edit: ["all"] for editors and admins, [] for viewers
#   admin:     ["all"] for admins (permanent delete), [] otherwise
# Inactive users get no entry, so they can't sign in.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p private

echo "SELECT email, role, editable_environments FROM app_user WHERE active = true ORDER BY email;" \
  | tests/surql.sh - -f \
  | python3 -I -c '
import json, sys
line = sys.stdin.read().strip().splitlines()[-1]
users = json.loads(line.split("  ", 1)[1])
out = ["# GENERATED by tests/sync_web_users.sh from the users table - do not edit by hand.",
       "# Simulated sign-in for api/flags.yaml: password \"demo\" for every active user."]
for u in users:
    role = u["role"]
    envs = ["development", "uat", "production"] if role == "admin" else \
           [e for e in (u.get("editable_environments") or "").split(",") if e] if role == "editor" else []
    flag_edit = ["all"] if role in ("editor", "admin") else []
    admin = ["all"] if role == "admin" else []
    out.append("%s: { principal: %s, role: %s, envs: %s, flag_edit: %s, admin: %s }" % (
        json.dumps(u["email"].lower() + ":demo"), json.dumps(u["email"].lower()), role,
        json.dumps(envs), json.dumps(flag_edit), json.dumps(admin)))
open("private/web-tokens.yaml", "w").write("\n".join(out) + "\n")
print("wrote private/web-tokens.yaml with %d users" % len(users))
'
